#!/usr/bin/env node
// Adapted from video-shotcraft, 2026-10-21: no demos/gallery/template dependency.
import { existsSync, lstatSync, mkdirSync, readdirSync, realpathSync, statSync, symlinkSync, unlinkSync, writeFileSync } from 'node:fs';
import { dirname, extname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';
const wb = join(dirname(fileURLToPath(import.meta.url)), '..');
const publicDir = join(wb, 'public');
mkdirSync(publicDir, {recursive: true});
const soundDir = join(wb, '../modules/audio/assets/arcade-motion');
const soundLink = join(publicDir, 'foundation-sfx');
if (existsSync(soundDir)) {
  try { if (lstatSync(soundLink).isSymbolicLink()) unlinkSync(soundLink); } catch {}
  if (!existsSync(soundLink)) symlinkSync(relative(publicDir, soundDir), soundLink);
}
const kindOf = {'.mp4':'video','.webm':'video','.mov':'video','.png':'image','.jpg':'image','.jpeg':'image','.webp':'image','.gif':'image','.svg':'image','.wav':'audio','.mp3':'audio','.m4a':'audio','.ogg':'audio','.flac':'audio'};
const media = [], sfx = [];
const scan = (dir, rel = '', ancestors = new Set()) => {
  const real = realpathSync(dir);
  if (ancestors.has(real)) return;
  const next = new Set([...ancestors, real]);
  for (const name of readdirSync(dir).sort()) {
    if (name.startsWith('.')) continue;
    const p = join(dir, name), file = rel ? `${rel}/${name}` : name;
    let st; try {st = statSync(p);} catch {continue;}
    if (st.isDirectory()) scan(p, file, next);
    else if (kindOf[extname(name).toLowerCase()]) {
      const kind = kindOf[extname(name).toLowerCase()];
      if (file.startsWith('foundation-sfx/')) {
        if (kind === 'audio') sfx.push({file, cat: 'Foundation', name: name.replace(/\.[^.]+$/, '')});
      } else media.push({file, dir: rel, name, kind});
    }
  }
};
scan(publicDir);
const banner = '// Generated by scripts/gen-index.mjs; do not edit.\n';
writeFileSync(join(wb, 'src/mediaManifest.ts'), banner +
  'export type MediaItem = { file: string; dir: string; name: string; kind: "video" | "image" | "audio" };\n' +
  `export const MEDIA_ITEMS: MediaItem[] = ${JSON.stringify(media)};\n` +
  'export type LibAudio = { file: string; cat: string; name: string };\n' +
  `export const SFX_LIB: LibAudio[] = ${JSON.stringify(sfx)};\nexport const BGM_LIB: LibAudio[] = [];\n`);
const link = join(wb, 'proj');
const linked = existsSync(link);
const manifest = linked && ['workbench.ts','workbench.tsx'].some(f => existsSync(join(link, f)));
const projectDir = linked ? dirname(realpathSync(link)) : '';
writeFileSync(join(wb, 'src/projMeta.ts'), banner + `export const PROJ_LINKED = ${linked};\nexport const PROJ_DIR = ${JSON.stringify(projectDir)};\nexport const PROJ_HAS_MANIFEST = ${manifest};\n`);
console.log(`gen-index: ${media.length} project media; ${sfx.length} Foundation sounds; manifest ${manifest ? projectDir : 'not linked'}`);
